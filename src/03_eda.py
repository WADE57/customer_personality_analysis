def format_pvalue(value):
    if pd.isna(value):
        return "Non disponible"

    if value == 0:
        return "< 1e-300"

    if value < 0.001:
        return f"{value:.2e}"

    return f"{value:.4f}"


def prepare_report_table(data, pvalue_columns=None):

    result = data.copy()

    if pvalue_columns is None:
        pvalue_columns = []

    for col in pvalue_columns:
        if col in result.columns:
            result[col] = result[col].apply(format_pvalue)

    return result


